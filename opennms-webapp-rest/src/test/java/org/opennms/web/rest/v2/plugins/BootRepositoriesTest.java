package org.opennms.web.rest.v2.plugins;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashSet;
import java.util.Set;

import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

public class BootRepositoriesTest {
    @Rule
    public TemporaryFolder folder = new TemporaryFolder();

    private static final String ASSEMBLED_SHAPE = String.join("\n",
            "################################################################################",
            "#    Licensed to the Apache Software Foundation (ASF) under one or more",
            "################################################################################",
            "",
            "# OPENNMS: Include the main product features file generated by the mvn:org.opennms.karaf/opennms project",
            "featuresRepositories = \\",
            "    mvn:org.apache.karaf.features/standard/4.4.9/xml/features, \\",
            "    mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/spring-legacy, \\",
            "    mvn:org.apache.karaf.features/framework/4.4.9/xml/features, \\",
            "    mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/karaf-extensions, \\",
            "    mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/features",
            "",
            "# OPENNMS: Parenthesize standard Karaf boot features, add OpenNMS product features",
            "featuresBoot = ( \\",
            "    aries-blueprint/4.4.9, \\",
            "    kar/4.4.9 \\",
            "  ), \\",
            "  opennms-api-layer,\\",
            "  opennms-karaf-health",
            "# Ensure that the 'opennms-karaf-health' feature is installed *last*",
            "",
            "#resourceRepositories=xml:http://host/path/to/index.xml",
            "featuresBootAsynchronous=false",
            "serviceRequirements=disable",
            "");

    private Path write(final String content) throws IOException {
        final Path cfg = folder.getRoot().toPath().resolve(BootRepositories.CFG_FILE_NAME);
        Files.write(cfg, content.getBytes(StandardCharsets.UTF_8));
        return cfg;
    }

    @Test
    public void parsesTheAssembledFileShape() throws IOException {
        final Set<String> repositories = BootRepositories.load(write(ASSEMBLED_SHAPE));
        final Set<String> expected = new LinkedHashSet<>(Arrays.asList(
                "mvn:org.apache.karaf.features/standard/4.4.9/xml/features",
                "mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/spring-legacy",
                "mvn:org.apache.karaf.features/framework/4.4.9/xml/features",
                "mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/karaf-extensions",
                "mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/features"));
        assertEquals(expected, repositories);
    }

    @Test
    public void ignoresOtherKeysAndCommentedRepositories() throws IOException {
        final Set<String> repositories = BootRepositories.load(write(String.join("\n",
                "#featuresRepositories = mvn:commented/out/1/xml/features",
                "featuresRepositoriesExtra = mvn:not/this/1/xml/features",
                "featuresBoot = a, b",
                "featuresRepositories=mvn:one/repo/1/xml/features,mvn:two/repo/2/xml/features",
                "resourceRepositories=xml:http://host/index.xml")));
        assertEquals(new LinkedHashSet<>(Arrays.asList(
                "mvn:one/repo/1/xml/features", "mvn:two/repo/2/xml/features")), repositories);
    }

    @Test
    public void singleLineWithColonSeparatorAndTrailingComma() throws IOException {
        final Set<String> repositories = BootRepositories.load(write("featuresRepositories: mvn:a/b/1/xml/features , ,mvn:c/d/2/xml/features,\n"));
        assertEquals(new LinkedHashSet<>(Arrays.asList(
                "mvn:a/b/1/xml/features", "mvn:c/d/2/xml/features")), repositories);
    }

    @Test
    public void continuationEndingAtEndOfFileIsKept() throws IOException {
        final Set<String> repositories = BootRepositories.load(write("featuresRepositories = \\\n    mvn:a/b/1/xml/features, \\\n    mvn:c/d/2/xml/features \\"));
        assertEquals(new LinkedHashSet<>(Arrays.asList(
                "mvn:a/b/1/xml/features", "mvn:c/d/2/xml/features")), repositories);
    }

    @Test
    public void missingFileYieldsEmptySet() {
        assertTrue(BootRepositories.load(folder.getRoot().toPath().resolve("nope.cfg")).isEmpty());
        assertTrue(BootRepositories.load(null).isEmpty());
    }

    @Test
    public void isCoreMatchesBootListOrOpennmsCoordinates() {
        final Set<String> boot = Collections.singleton("mvn:org.apache.karaf.features/standard/4.4.9/xml/features");
        assertTrue(BootRepositories.isCore("mvn:org.apache.karaf.features/standard/4.4.9/xml/features", boot));
        assertTrue(BootRepositories.isCore(" mvn:org.apache.karaf.features/standard/4.4.9/xml/features ", boot));
        assertTrue(BootRepositories.isCore("mvn:org.opennms.karaf/opennms/37.0.0-SNAPSHOT/xml/features", Collections.emptySet()));
        assertTrue(BootRepositories.isCore("mvn:org.opennms.integration.api/karaf-features/2.0.1/xml", Collections.emptySet()));
        assertFalse(BootRepositories.isCore("mvn:org.opennms.plugins.alec/alec-karaf-features/3.0.0/xml", boot));
        assertFalse(BootRepositories.isCore(null, boot));
    }
}
